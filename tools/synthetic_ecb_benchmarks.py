#!/usr/bin/env python3
"""Generate the SYNTHETIC ECB-style credit-risk benchmark file tests/params/synthetic_ecb_benchmarks.csv.

The values are invented, deterministic and only plausible in magnitude. They are NOT ECB benchmark parameters
(those are confidential, per exercise, and never committed). The file has the layout of Sora's benchmark format
(plans/09_risk_parameters.md, "Benchmark file format"), so the application rule (EBA MN 2027 draft paras 115-117
and 146) can be tested on the reference dataset.

    python tools/synthetic_ecb_benchmarks.py -o tests/params/synthetic_ecb_benchmarks.csv [--years 2025 2026 2027]

Coverage follows the MN: no benchmarks for debt securities other than general governments, nor for loans to
central banks (2027 draft MN footnote 13). Countries: the EU countries among the reference dataset's top-10
buckets, plus the aggregates EU and WR (rest of the world) used as the country fallback.
"""

from __future__ import annotations

import argparse
from pathlib import Path

HEADER = "instrument,portfolio,country,scenario,year,parameter,value"
PARAMETERS = ("pd12m_s1", "pd12m_s2", "tr1_2", "tr2_1", "lgd_s1", "lgd_s2", "lgd_s3", "lrlt_s2")

# Baseline year-1 levels per pivot asset class: pd12m_s1, pd12m_s2, tr1_2, tr2_1, lgd (S1/S2), lgd_s3, lrlt_s2.
PIVOTS = {
    ("LOANS", "GG"): (0.0015, 0.040, 0.020, 0.300, 0.300, 0.400, 0.030),
    ("LOANS", "CI"): (0.0020, 0.050, 0.030, 0.300, 0.400, 0.500, 0.040),
    ("LOANS", "OFC"): (0.0060, 0.080, 0.050, 0.280, 0.400, 0.550, 0.070),
    ("LOANS", "NFC_SME_CRE"): (0.0200, 0.140, 0.080, 0.250, 0.300, 0.450, 0.090),
    ("LOANS", "NFC_SME_OTHER"): (0.0180, 0.130, 0.070, 0.260, 0.400, 0.550, 0.100),
    ("LOANS", "NFC_LARGE_CRE"): (0.0120, 0.110, 0.060, 0.250, 0.280, 0.420, 0.070),
    ("LOANS", "NFC_LARGE_OTHER"): (0.0100, 0.100, 0.050, 0.270, 0.380, 0.520, 0.080),
    ("LOANS", "HH_HOUSE"): (0.0060, 0.070, 0.040, 0.300, 0.120, 0.250, 0.020),
    ("LOANS", "HH_CONS"): (0.0200, 0.150, 0.060, 0.220, 0.600, 0.750, 0.180),
    ("LOANS", "HH_OTHER"): (0.0150, 0.120, 0.050, 0.240, 0.450, 0.600, 0.120),
    ("DEBT_SEC", "GG"): (0.0010, 0.030, 0.015, 0.300, 0.300, 0.400, 0.025),
}
COUNTRIES = {"BE": 0.90, "DE": 0.85, "ES": 1.10, "FR": 1.00, "LU": 0.80, "PL": 1.20, "EU": 1.00, "WR": 1.15}
# Multipliers per projection year 1..3: (PD and TR1-2, TR2-1, LGD/LR).
PATHS = {
    "baseline": ((1.00, 1.00, 1.00), (1.03, 0.98, 1.01), (1.02, 0.99, 1.01)),
    "adverse": ((1.60, 0.80, 1.10), (2.00, 0.70, 1.20), (1.80, 0.75, 1.25)),
}


def rows(years: list[int]) -> list[str]:
    out = []
    for (instrument, portfolio), (pd1, pd2, t12, t21, lgd, lgd3, lrlt) in PIVOTS.items():
        for country, cm in COUNTRIES.items():
            for scenario, path in PATHS.items():
                for year, (m_pd, m_cure, m_lgd) in zip(years, path):
                    v = {
                        "pd12m_s1": pd1 * cm * m_pd,
                        "pd12m_s2": min(pd2 * cm * m_pd, 0.6),
                        "tr1_2": t12 * cm * m_pd,
                        "tr2_1": t21 * m_cure / cm,
                        "lgd_s1": min(lgd * m_lgd, 0.95),
                        "lgd_s2": min(lgd * m_lgd, 0.95),
                        "lgd_s3": min(lgd3 * m_lgd, 0.95),
                        "lrlt_s2": min(lrlt * cm * m_pd ** 0.5 * m_lgd, 0.95),
                    }
                    v["tr2_1"] = min(v["tr2_1"], 1 - v["pd12m_s2"])
                    for p in PARAMETERS:
                        out.append(f"{instrument},{portfolio},{country},{scenario},{year},{p},{v[p]:.6f}")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", type=Path, required=True)
    ap.add_argument("--years", type=int, nargs=3, default=[2025, 2026, 2027],
                    help="scenario years of projection years 1..3 (the scenario's year_map)")
    args = ap.parse_args()
    text = ("# SYNTHETIC ECB-style credit-risk benchmarks for tests. NOT ECB values. "
            "Generated by tools/synthetic_ecb_benchmarks.py.\n" + HEADER + "\n" + "\n".join(rows(args.years)) + "\n")
    args.out.write_text(text)


if __name__ == "__main__":
    main()
